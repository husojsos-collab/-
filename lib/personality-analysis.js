// ============ !تحليل_شخصية - تحليل مرح (مو جدي) لعضو بناءً على آخر رسايله ============

const ANALYSIS_SYSTEM_PROMPT = `
انت أداة تحليل شخصية مرحة بالعربي (لهجة خفيفة مفهومة، مش رسمية). بعطيك كم رسالة كتبها شخص بجروب واتساب،
ورد عليّ بتحليل شخصية قصير ومرح (3-4 أسطر بحد أقصى) بأسلوب خفيف الظل مش جدي أبداً - زي تحليل فأل أو لعبة،
مش تحليل نفسي حقيقي. لا تخترع معلومات حساسة أو تحكم قاسي عليه، خليه إيجابي أو محايد ومضحك بس.
ممنوع أي استنتاج طبي أو نفسي حقيقي أو حكم شخصي جارح. رجع النص بس بدون مقدمات زي "تحليل الشخصية:".
`.trim();

function buildUserPrompt(messages) {
  const sample = messages.slice(-15).map((m) => `- ${m.text}`).join('\n');
  return `هذي آخر رسايل الشخص بالجروب:\n${sample}\n\nاكتب تحليل شخصية مرح قصير عنه.`;
}

function analysisBanner(nameTag, analysisText) {
  return [
    '⌬──══─┈•⤣🔍⤤•┈─══──⌬',
    '🔍 *تـحـلـيـل شـخـصـيـة*',
    `👤 ${nameTag}`,
    '',
    analysisText,
    '',
    '(تحليل للمرح بس، مو جدي 😄)',
    '⌬──══─┈•⤣🔍⤤•┈─══──⌬'
  ].join('\n');
}

function notEnoughDataMessage() {
  return 'محتاج شوية رسايل من هاد العضو الأول عشان أقدر أحلل، خليه يحكي شوي بالجروب وجرب مرة تانية 🙂';
}

module.exports = {
  ANALYSIS_SYSTEM_PROMPT,
  buildUserPrompt,
  analysisBanner,
  notEnoughDataMessage
};
