// ============ !توقع - فأل يومي مرح (خفيف مو جدي) ============

const FORTUNES = [
  'اليوم يومك، افرح وارتاح شوي 😌',
  'يمكن يوصلك خبر حلو ما تتوقعه اليوم 🍀',
  'خلك مبسوط اليوم، الجو نفسيتك ماشي معاك 🌤️',
  'فرصة حلوة بتجيك، لا تفوتها 🎯',
  'اليوم مناسب تتواصل مع صديق قديم 📞',
  'خل بالك من قهوتك الثانية، بتخليك نشيط زيادة ☕',
  'اليوم يوم زين تسوي فيه شي جديد 🌱',
  'حظك اليوم متوسط، بس مزاجك هو اللي بيحدد يومك 😄',
  'ممكن تسمع خبر يفرحك من قريب أو صديق 🎉',
  'اليوم يبان عليك نشيط، استغل الطاقة هاي 🔥',
  'خلك صبور اليوم، الأمور بتمشي أحسن من المتوقع ⏳',
  'يوم زين للراحة والاسترخاء، لا تشغل بالك كثير 🛋️'
];

function getDailyFortune() {
  return FORTUNES[Math.floor(Math.random() * FORTUNES.length)];
}

function fortuneBanner(nameTag) {
  return [
    '⌬──══─┈•⤣🎀⤤•┈─══──⌬',
    '🔮 *تـوقـع الـيـوم:*',
    '',
    `> ${nameTag ? nameTag + '، ' : ''}${getDailyFortune()} ✨🌸`,
    '⌬──══─┈•⤣🎀⤤•┈─══──⌬'
  ].join('\n');
}

module.exports = {
  getDailyFortune,
  fortuneBanner
};
